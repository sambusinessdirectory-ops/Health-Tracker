  function interpolate(template, variables = {}) {
    return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key) =>
      Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : match,
    );
  }

  function normalizeLanguage(value) {
    return value === "zh-Hant" ? "zh-Hant" : "en";
  }

  function translate(key, variables = {}, language = "en") {
    const normalized = normalizeLanguage(language);
    const template = catalogs[normalized]?.[key] ?? catalogs.en[key] ?? key;
    return interpolate(template, variables);
  }

  function locale(language) {
    return normalizeLanguage(language) === "zh-Hant" ? "zh-HK" : "en-GB";
  }

  window.HealthI18n = Object.freeze({ catalogs, locale, normalizeLanguage, translate });
